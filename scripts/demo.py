"""Offline end-to-end demo.

Runs the full multi-agent workflow with deterministic fakes (no API keys, no
network) and writes a human-readable walkthrough to ``docs/example_output.md``.

Usage (from the repository root):

    python scripts/demo.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.config import Settings  # noqa: E402
from app.database.session import get_session_factory, init_db, init_engine  # noqa: E402
from app.services.research_service import ResearchService  # noqa: E402
from tests.fakes import FakeFetcher, FakeLLM, FakeSearch  # noqa: E402

QUESTION = (
    "Analyze the current adoption of Agentic AI in India, its impact on fresher "
    "hiring, the skills companies expect, and career opportunities over the "
    "next three years."
)
DB_PATH = ROOT / "data" / "demo.db"
OUTPUT_PATH = ROOT / "docs" / "example_output.md"


def fake_tool_factory(_settings: Settings):
    return FakeLLM(), FakeSearch(num_results=3), FakeFetcher()


def main() -> int:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    settings = Settings(database_url=f"sqlite:///{DB_PATH.as_posix()}")
    init_engine(settings.database_url)
    init_db()

    service = ResearchService(
        settings=settings,
        session_factory=get_session_factory(),
        tool_factory=fake_tool_factory,
        checkpointer_provider=lambda _s: None,
    )

    print("Running offline demo (fake LLM + search + fetcher)...")
    created = service.create_research(QUESTION)
    service.run_research(created.research_id, QUESTION)

    status = service.get_status(created.research_id)
    report = service.get_report(created.research_id)
    sources = service.get_sources(created.research_id)
    service.shutdown()

    markdown = render_markdown(status, report, sources)
    OUTPUT_PATH.write_text(markdown, encoding="utf-8")

    print(f"  status            : {status.status}")
    print(f"  stage             : {status.stage}")
    print(f"  sources           : {status.progress.sources_total}")
    print(f"  evidence          : {status.progress.evidence_total}")
    print(f"  verified claims   : {status.progress.verified_claims}")
    print(f"  review passed     : {report.review.passed if report and report.review else 'n/a'}")
    print(f"  report written to : {OUTPUT_PATH.relative_to(ROOT)}")
    return 0


def render_markdown(status, report, sources) -> str:  # noqa: ANN001
    lines = [
        "# Example Output (offline demo)",
        "",
        "> Generated by `python scripts/demo.py` using deterministic fakes — no API",
        "> keys and no network. The runtime uses the real OpenAI + Tavily tools.",
        "",
        "## Run summary",
        "",
        f"**Question:** {status.question}",
        "",
        f"- Status: `{status.status}`",
        f"- Stage: `{status.stage}`",
        f"- Sources discovered: {status.progress.sources_total}",
        f"- Evidence items extracted: {status.progress.evidence_total}",
        f"- Verified claims: {status.progress.verified_claims}",
    ]
    if report and report.review:
        lines.append(f"- Review passed: `{report.review.passed}` (score {report.review.score})")
    lines += ["", "## Report", "", report.markdown if report else "_no report_", ""]
    lines += ["## Verification", ""]
    if sources and sources.evidence:
        lines += ["| # | Claim | Status | Source |", "|---|-------|--------|--------|"]
        for e in sources.evidence:
            lines.append(f"| {e.id} | {e.claim} | {e.verification_status} | {e.source_id} |")
    else:
        lines.append("_no evidence_")
    lines += ["", "## Sources", ""]
    if sources and sources.sources:
        for s in sources.sources:
            lines.append(f"- **[{s.id}] {s.title}** — {s.url}")
    else:
        lines.append("_no sources_")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    raise SystemExit(main())
